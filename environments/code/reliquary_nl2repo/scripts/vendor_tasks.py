"""Fetch NL2Repo-Bench's 104 tasks into `reliquary_nl2repo/tasks/`, checked by digest.

Upstream (multimodal-art-projection/NL2RepoBench) ships no license, so the task files are
not committed: `reliquary_nl2repo/_source.py` is, with the sha256 of every file. This
script copies, per task, `start.md`, `test_case_count.txt`, `test_commands.json` and
`test_files.json` from a clean checkout at the pinned commit, and refuses any file whose
digest is not the pinned one. Run it before `uv build` (the wheel then carries the tasks)
and before any test that loads a task.

The checkout is read as data: nothing in it is executed or imported.

    git clone https://github.com/multimodal-art-projection/NL2RepoBench.git /tmp/nl2repo
    git -C /tmp/nl2repo checkout 781a1da1ee41fb8edb0bed22f586d69111610edf
    python scripts/vendor_tasks.py /tmp/nl2repo
    python scripts/vendor_tasks.py /tmp/nl2repo --write-source   # re-pin (new version)
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import shutil
import subprocess
from pathlib import Path

COMMIT = "781a1da1ee41fb8edb0bed22f586d69111610edf"
UPSTREAM = "https://github.com/multimodal-art-projection/NL2RepoBench"
PACKAGE = Path(__file__).resolve().parent.parent / "reliquary_nl2repo"
TASKS = PACKAGE / "tasks"
SOURCE = PACKAGE / "_source.py"
FILES = ("start.md", "test_case_count.txt", "test_commands.json", "test_files.json")
EXPECTED_TASKS = 104


def git(checkout: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(checkout), *args], check=True,
                          capture_output=True, text=True).stdout


def pinned() -> dict[str, str]:
    spec = importlib.util.spec_from_file_location("_source", SOURCE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    if module.COMMIT != COMMIT:
        raise SystemExit(f"_source.py pins {module.COMMIT}, this script {COMMIT}")
    return dict(module.FILES)


def write_source(digests: dict[str, str]) -> None:
    lines = [
        '"""Generated by scripts/vendor_tasks.py: do not edit.',
        "",
        "The upstream commit the tasks are fetched from, and the sha256 of every file",
        "`tasks/` must hold (path relative to `tasks/`). Upstream ships no license: the",
        "files themselves are fetched by the script, never committed.",
        '"""',
        "",
        f'UPSTREAM = "{UPSTREAM}"',
        f'COMMIT = "{COMMIT}"',
        "FILES = {",
        *(f'    "{rel}": "{digest}",' for rel, digest in sorted(digests.items())),
        "}",
        "",
    ]
    SOURCE.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("checkout", type=Path)
    parser.add_argument("--write-source", action="store_true",
                        help="rewrite _source.py from the checkout instead of checking it")
    args = parser.parse_args()
    checkout = args.checkout.resolve()
    if git(checkout, "rev-parse", "HEAD").strip() != COMMIT:
        raise SystemExit(f"{checkout} is not at {COMMIT}")
    if git(checkout, "status", "--porcelain", "--", "test_files").strip():
        raise SystemExit(f"{checkout}/test_files has local changes")
    task_dirs = sorted(p for p in (checkout / "test_files").iterdir() if p.is_dir())
    if len(task_dirs) != EXPECTED_TASKS:
        raise SystemExit(f"expected {EXPECTED_TASKS} tasks, found {len(task_dirs)}")
    digests: dict[str, str] = {}
    blobs: dict[str, bytes] = {}
    for task_dir in task_dirs:
        for name in FILES:
            path = task_dir / name
            if path.is_symlink() or not path.is_file():
                raise SystemExit(f"{path}: missing or not a regular file")
            rel = f"{task_dir.name}/{name}"
            blobs[rel] = path.read_bytes()
            digests[rel] = hashlib.sha256(blobs[rel]).hexdigest()
    if args.write_source:
        write_source(digests)
    else:
        expected = pinned()
        if expected != digests:
            changed = sorted(k for k in expected.keys() | digests.keys()
                             if expected.get(k) != digests.get(k))
            raise SystemExit(f"{len(changed)} files differ from _source.py: {changed[:10]}")
    if TASKS.exists():
        shutil.rmtree(TASKS)
    for rel, data in blobs.items():
        target = TASKS / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print(f"vendored {len(task_dirs)} tasks ({len(blobs)} files) at {COMMIT}")


if __name__ == "__main__":
    main()
