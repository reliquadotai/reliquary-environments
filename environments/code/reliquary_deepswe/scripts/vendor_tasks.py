"""Vendor DeepSWE v1.1's 113 tasks from a checkout of datacurve-ai/deep-swe, once.

Copies `tasks/<id>/` (task.toml, instruction.md, pre_artifacts.sh, environment/,
tests/, solution/) into `reliquary_deepswe/tasks/<id>/` and writes
`reliquary_deepswe/_source.py`: the upstream commit and the sha256 of every vendored
file. `_source.py` is a `.py` file on purpose: a bridged env's identity digests the
package's `.py` files only, so the task files are bound to it through this table, and
the taskset refuses a task whose files do not match it.

The checkout is read as data: nothing in it is executed or imported.

    git clone https://github.com/datacurve-ai/deep-swe.git /tmp/deep-swe
    git -C /tmp/deep-swe checkout 8cae5984d5dd0ee37445beff0e928dc10c331116
    python scripts/vendor_tasks.py /tmp/deep-swe
"""

from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
from pathlib import Path

COMMIT = "8cae5984d5dd0ee37445beff0e928dc10c331116"
PACKAGE = Path(__file__).resolve().parent.parent / "reliquary_deepswe"
TASKS = PACKAGE / "tasks"
SOURCE = PACKAGE / "_source.py"
EXPECTED_TASKS = 113


def head(checkout: Path) -> str:
    return subprocess.run(["git", "-C", str(checkout), "rev-parse", "HEAD"], check=True,
                          capture_output=True, text=True).stdout.strip()


def clean(checkout: Path) -> bool:
    status = subprocess.run(["git", "-C", str(checkout), "status", "--porcelain", "--", "tasks"],
                            check=True, capture_output=True, text=True).stdout
    return not status.strip()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("checkout", type=Path)
    args = parser.parse_args()
    checkout = args.checkout.resolve()
    if head(checkout) != COMMIT or not clean(checkout):
        raise SystemExit(f"{checkout} must be a clean checkout of {COMMIT}")
    task_dirs = sorted(p.parent for p in (checkout / "tasks").glob("*/task.toml"))
    if len(task_dirs) != EXPECTED_TASKS:
        raise SystemExit(f"expected {EXPECTED_TASKS} tasks, found {len(task_dirs)}")
    if TASKS.exists():
        shutil.rmtree(TASKS)
    digests: dict[str, str] = {}
    for task_dir in task_dirs:
        for path in sorted(task_dir.rglob("*")):
            if path.is_symlink():
                raise SystemExit(f"{path}: a symlink in the upstream task")
            if not path.is_file():
                continue
            rel = path.relative_to(checkout / "tasks").as_posix()
            data = path.read_bytes()
            target = TASKS / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            if path.stat().st_mode & 0o111:
                target.chmod(0o755)
            digests[rel] = hashlib.sha256(data).hexdigest()
    lines = [
        '"""Generated by scripts/vendor_tasks.py: do not edit.',
        "",
        "The upstream commit the tasks under `tasks/` were copied from, and the sha256 of",
        "every vendored file (path relative to `tasks/`).",
        '"""',
        "",
        'UPSTREAM = "https://github.com/datacurve-ai/deep-swe"',
        f'COMMIT = "{COMMIT}"',
        "FILES = {",
        *(f'    "{rel}": "{digest}",' for rel, digest in sorted(digests.items())),
        "}",
        "",
    ]
    SOURCE.write_text("\n".join(lines))
    print(f"{len(task_dirs)} tasks, {len(digests)} files vendored at {COMMIT[:7]}")


if __name__ == "__main__":
    main()
